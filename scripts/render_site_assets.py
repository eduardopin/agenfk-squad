#!/usr/bin/env python3
"""Render the landing-page terminal capture and social card.

The terminal source is generated by running hooks/squad-watch.py over the same
synthetic usage pattern as tests/test_watch.py, with HOME isolated in a
temporary directory. The terminal is drawn flat at 14px in two widths (desktop
panel and phone). The social card is 1200x630, rendered from HTML with headless
Chrome (``CHROME`` overrides the binary) and Archivo from Google Fonts.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MESSAGE = ROOT / "site" / "img" / "watcher-message.txt"
TERMINAL = ROOT / "site" / "img" / "watcher-terminal.svg"
TERMINAL_NARROW = ROOT / "site" / "img" / "watcher-terminal-narrow.svg"
OG = ROOT / "site" / "og.png"
HOOK = ROOT / "hooks" / "squad-watch.py"


def generate_message() -> str:
    """Run the real watcher with a 550k/90%-reread synthetic transcript."""
    context = 550_000
    reread_share = 0.9
    burn = 0.6
    session_budget = 20_000_000
    turns = max(10, round(reread_share * burn * session_budget / (context * 0.1)))
    reread = turns * context * 0.1
    new_work = reread * (1 - reread_share) / reread_share

    with tempfile.TemporaryDirectory(prefix="watcher-") as home:
        transcript = Path(home) / "synthetic.jsonl"
        records = [
            {
                "type": "assistant",
                "isSidechain": False,
                "requestId": f"synthetic-{index}",
                "message": {
                    "usage": {
                        "cache_read_input_tokens": context,
                        "output_tokens": int(new_work / turns / 5),
                    }
                },
            }
            for index in range(turns)
        ]
        transcript.write_text(
            "".join(json.dumps(record) + "\n" for record in records),
            encoding="utf-8",
        )
        payload = {
            "hook_event_name": "PostToolUse",
            "session_id": "synthetic-landing-page",
            "transcript_path": str(transcript),
            "tool_name": "Bash",
            "tool_input": {"command": "true"},
            "cwd": home,
        }
        env = {
            key: value
            for key, value in os.environ.items()
            if not key.startswith(("SQUAD_", "HERDR_"))
        }
        env.update({"HOME": home, "CLAUDE_SESSION_BUDGET": str(session_budget)})
        result = subprocess.run(
            [sys.executable, str(HOOK)],
            input=json.dumps(payload),
            capture_output=True,
            text=True,
            env=env,
            check=True,
        )

    try:
        response = json.loads(result.stdout)
        message = response["hookSpecificOutput"]["additionalContext"]
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        raise SystemExit(f"Watcher did not return a hook message: {result.stdout!r}") from exc
    if "PROACTIVE HANDOFF" not in message:
        raise SystemExit(f"Expected a proactive handoff, got: {message!r}")
    MESSAGE.write_text(message.strip() + "\n", encoding="utf-8")
    return message.strip()


# Pin Open 1.0.0 terminal and light tokens (site/assets/pin-open-1.0.0.css).
TERM_BG = "#121417"
TERM_INK = "#e3e7e4"
TERM_PROMPT = "#8fd9bd"
GROUND = "#f3f3f0"
INK = "#15181b"
INK_MUTED = "#4d555b"
GREEN = "#0b6b50"
FONT = 14  # px; each variant is shown at no less than its own width, so text stays >= 14px
LINE = 21
# (path, width, wrap columns). Columns assume 0.62em per monospace glyph, wider
# than DejaVu Sans Mono, Menlo and Consolas, so no line overflows on any of them.
VARIANTS = (
    (TERMINAL, 440, 46),
    (TERMINAL_NARROW, 288, 28),
)
WIDTH, HEIGHT = 1200, 630
FONTS_URL = (
    "https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,100..900"
    "&family=Martian+Mono:wdth,wght@75..112.5,100..800&display=block"
)


def render_terminal(message: str) -> None:
    """Draw the watcher message flat, 14px text, one SVG per layout width."""
    for path, width, columns in VARIANTS:
        lines = textwrap.wrap(
            message,
            width=columns,
            break_long_words=True,
            break_on_hyphens=False,
        )
        pad = 16 if width > 300 else 12
        top = pad + FONT
        height = top + (len(lines) - 1) * LINE + pad + 4
        nodes = "".join(
            f'<text x="{pad}" y="{top + index * LINE}"'
            f'{" class=\"h\"" if index == 0 else ""}>{html.escape(line)}</text>'
            for index, line in enumerate(lines)
        )
        svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
  <title>Example squad-watch hook output from a synthetic transcript</title>
  <desc>Example hook output from a synthetic transcript at an artificial 550 thousand tokens of context, generated by scripts/render_site_assets.py.</desc>
  <style>text {{ font: {FONT}px ui-monospace, "DejaVu Sans Mono", SFMono-Regular, Menlo, Consolas, monospace; fill: {TERM_INK}; white-space: pre; }} .h {{ fill: {TERM_PROMPT}; }}</style>
  <rect width="{width}" height="{height}" fill="{TERM_BG}"/>
  {nodes}
</svg>
"""
        path.write_text(svg, encoding="utf-8")


def chrome() -> str:
    for candidate in (os.environ.get("CHROME"), "google-chrome", "chromium", "chromium-browser"):
        if candidate and shutil.which(candidate):
            return shutil.which(candidate)  # type: ignore[return-value]
    raise SystemExit("Chrome or Chromium not found; set CHROME to its path")


def png_size(path: Path) -> tuple[int, int]:
    header = path.read_bytes()[:24]
    if header[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"{path} is not a PNG")
    return struct.unpack(">II", header[16:24])


def og_page() -> str:
    """The Pin Open social image: favicon, name, one accent rule, one line, URL."""
    favicon = (ROOT / "site" / "favicon.svg").as_uri()
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<link rel="stylesheet" href="{FONTS_URL}">
<style>
html,body{{margin:0;width:{WIDTH}px;height:{HEIGHT}px;overflow:hidden;background:{GROUND};color:{INK};font-family:Archivo,sans-serif}}
.fav{{position:absolute;left:64px;top:64px;width:96px;height:96px}}
h1{{position:absolute;left:64px;top:196px;margin:0;font-size:80px;line-height:.94;font-weight:780;font-stretch:118%;letter-spacing:-.035em}}
.rule{{position:absolute;left:64px;top:300px;width:264px;height:8px;background:{GREEN}}}
p{{position:absolute;left:64px;top:344px;width:1000px;margin:0;font-size:40px;line-height:1.15;font-weight:650;letter-spacing:-.01em}}
.url{{position:absolute;left:64px;top:500px;font-family:"Martian Mono",monospace;font-size:24px;color:{INK_MUTED}}}
</style></head><body>
<img class="fav" src="{favicon}" alt="">
<h1>AgenFK Squad</h1><div class="rule"></div>
<p>Guardrails for parallel Claude Code sessions: context budgets, independent review and one merge at a time.</p>
<div class="url">eduardopin.github.io/agenfk-squad</div>
</body></html>"""


def render_og() -> None:
    """Render site/og.png at 1200x630 from HTML with headless Chrome (needs Google Fonts)."""
    with tempfile.TemporaryDirectory() as tmp:
        page = Path(tmp) / "og.html"
        page.write_text(og_page(), encoding="utf-8")
        shot = Path(tmp) / "og.png"
        subprocess.run(
            [chrome(), "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
             f"--window-size={WIDTH},{HEIGHT}", "--virtual-time-budget=10000", f"--user-data-dir={tmp}/profile",
             f"--screenshot={shot}", page.as_uri()],
            check=True, capture_output=True,
        )
        if png_size(shot) != (WIDTH, HEIGHT):
            raise SystemExit(f"rendered {png_size(shot)}, expected {(WIDTH, HEIGHT)}")
        shutil.copyfile(shot, OG)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--terminal-only", action="store_true", help="skip rendering site/og.png")
    parser.add_argument("--reuse-message", action="store_true", help="draw the committed watcher-message.txt instead of rerunning the hook")
    args = parser.parse_args()
    message = MESSAGE.read_text(encoding="utf-8").strip() if args.reuse_message else generate_message()
    render_terminal(message)
    if not args.terminal_only:
        render_og()
    print(f"rendered {TERMINAL.relative_to(ROOT)} and {TERMINAL_NARROW.relative_to(ROOT)}")
    if not args.terminal_only:
        print(f"rendered {OG.relative_to(ROOT)} (1200x630)")


if __name__ == "__main__":
    main()
