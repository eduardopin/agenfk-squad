#!/usr/bin/env python3
"""Render the landing-page terminal capture and social card.

The terminal source is generated by running hooks/squad-watch.py over the same
synthetic usage pattern as tests/test_watch.py, with HOME isolated in a
temporary directory. The social card uses Pillow with local system fonts; no
font or browser download is used.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import struct
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
MESSAGE = ROOT / "site" / "img" / "watcher-message.txt"
TERMINAL = ROOT / "site" / "img" / "watcher-terminal.svg"
OG = ROOT / "site" / "og.png"
HOOK = ROOT / "hooks" / "squad-watch.py"


def generate_message() -> str:
    """Run the real watcher with a 550k/90%-reread synthetic transcript."""
    context = 550_000
    reread_share = 0.9
    burn = 0.6
    session_budget = 20_000_000
    turns = max(10, round(reread_share * burn * session_budget / (context * 0.1)))
    reread = turns * context * 0.1
    new_work = reread * (1 - reread_share) / reread_share

    with tempfile.TemporaryDirectory(prefix="watcher-") as home:
        transcript = Path(home) / "synthetic.jsonl"
        records = [
            {
                "type": "assistant",
                "isSidechain": False,
                "requestId": f"synthetic-{index}",
                "message": {
                    "usage": {
                        "cache_read_input_tokens": context,
                        "output_tokens": int(new_work / turns / 5),
                    }
                },
            }
            for index in range(turns)
        ]
        transcript.write_text(
            "".join(json.dumps(record) + "\n" for record in records),
            encoding="utf-8",
        )
        payload = {
            "hook_event_name": "PostToolUse",
            "session_id": "synthetic-landing-page",
            "transcript_path": str(transcript),
            "tool_name": "Bash",
            "tool_input": {"command": "true"},
            "cwd": home,
        }
        env = {
            key: value
            for key, value in os.environ.items()
            if not key.startswith(("SQUAD_", "HERDR_"))
        }
        env.update({"HOME": home, "CLAUDE_SESSION_BUDGET": str(session_budget)})
        result = subprocess.run(
            [sys.executable, str(HOOK)],
            input=json.dumps(payload),
            capture_output=True,
            text=True,
            env=env,
            check=True,
        )

    try:
        response = json.loads(result.stdout)
        message = response["hookSpecificOutput"]["additionalContext"]
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        raise SystemExit(f"Watcher did not return a hook message: {result.stdout!r}") from exc
    if "PROACTIVE HANDOFF" not in message:
        raise SystemExit(f"Expected a proactive handoff, got: {message!r}")
    MESSAGE.write_text(message.strip() + "\n", encoding="utf-8")
    return message.strip()


def render_terminal(message: str) -> None:
    lines = textwrap.wrap(
        message,
        width=103,
        break_long_words=False,
        break_on_hyphens=False,
        subsequent_indent="  ",
    )
    width = 1440
    top = 102
    line_height = 36
    height = top + len(lines) * line_height + 62
    text_nodes = []
    for index, line in enumerate(lines):
        fill = "#72e2b7" if index == 0 else "#dce4ed"
        text_nodes.append(
            f'<text x="50" y="{top + index * line_height}" fill="{fill}">'
            f"{html.escape(line)}</text>"
        )

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
  <title>Example squad-watch hook output from a synthetic transcript</title>
  <desc>Example hook output from a synthetic transcript at an artificial 550 thousand tokens of context.</desc>
  <rect width="{width}" height="{height}" fill="#0d1117"/>
  <style>text {{ font: 22px ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace; }}</style>
  {''.join(text_nodes)}
</svg>
"""
    TERMINAL.write_text(svg, encoding="utf-8")


def font_file(pattern: str) -> str:
    """Ask fontconfig for a local system font without downloading anything."""
    try:
        return subprocess.check_output(
            ["fc-match", "-f", "%{file}", pattern], text=True
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "DejaVuSans.ttf"


def render_og() -> None:
    try:
        from PIL import Image, ImageDraw, ImageFilter, ImageFont
    except ImportError as exc:
        raise SystemExit("Rendering site/og.png requires Pillow.") from exc

    width, height = 1280, 640
    image = Image.new("RGB", (width, height), "#0b0e12")
    draw = ImageDraw.Draw(image)

    for y in range(height):
        mix = y / height
        color = tuple(round(a + (b - a) * mix) for a, b in zip((11, 14, 18), (17, 24, 33)))
        draw.line((0, y, width, y), fill=color)
    for x in range(0, width, 32):
        draw.line((x, 0, x, height), fill="#151c24", width=1)
    for y in range(0, height, 32):
        draw.line((0, y, width, y), fill="#151c24", width=1)

    glow = Image.new("RGBA", image.size, (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse((810, -150, 1360, 400), fill=(40, 145, 104, 90))
    glow = glow.filter(ImageFilter.GaussianBlur(95))
    image = Image.alpha_composite(image.convert("RGBA"), glow)
    draw = ImageDraw.Draw(image)

    sans = font_file("sans-serif")
    bold = font_file("sans-serif:style=Bold")
    mono = font_file("monospace")
    title_font = ImageFont.truetype(bold, 65)
    body_font = ImageFont.truetype(sans, 25)
    brand_font = ImageFont.truetype(mono, 21)
    node_font = ImageFont.truetype(mono, 17)
    tag_font = ImageFont.truetype(mono, 15)

    draw.rounded_rectangle((70, 61, 118, 109), radius=14, fill="#11161d", outline="#4b5a69", width=1)
    draw.text((82, 75), "A/", font=brand_font, fill="#72e2b7")
    draw.text((132, 72), "agenfk-squad", font=brand_font, fill="#72e2b7")

    headline = "Parallel Claude Code, with someone watching the blind spots."
    title_lines = textwrap.wrap(headline, width=24)
    draw.multiline_text((70, 164), "\n".join(title_lines), font=title_font, fill="#f0f2f4", spacing=2)
    draw.text(
        (70, 438),
        "Context budgets. Bounded dispatch. Independent review.",
        font=body_font,
        fill="#aeb8c4",
    )
    draw.text((70, 474), "One merge turn at a time.", font=body_font, fill="#aeb8c4")

    rail_x, rail_y, rail_w = 928, 70, 282
    nodes = ("squad-watch", "main session", "role-limited agents", "AgenFK gates", "merge queue")
    for index, node in enumerate(nodes):
        y = rail_y + index * 99
        first = index == 0
        draw.rounded_rectangle(
            (rail_x, y, rail_x + rail_w, y + 58),
            radius=14,
            fill="#173b31" if first else "#111720",
            outline="#55d6a4" if first else "#3a4655",
            width=1,
        )
        draw.text((rail_x + 18, y + 18), node, font=node_font, fill="#72e2b7" if first else "#dce4ed")
        if index < len(nodes) - 1:
            draw.line((rail_x + 30, y + 64, rail_x + 30, y + 93), fill="#55d6a4", width=2)

    tag_x = 70
    for tag in ("12 agents", "Python hooks", "standard library"):
        box = draw.textbbox((0, 0), tag, font=tag_font)
        tag_w = box[2] - box[0] + 24
        draw.rounded_rectangle((tag_x, 558, tag_x + tag_w, 592), radius=17, fill="#111720", outline="#35404d")
        draw.text((tag_x + 12, 566), tag, font=tag_font, fill="#aeb8c4")
        tag_x += tag_w + 13

    image.convert("RGB").save(OG, format="PNG", optimize=True)

    with OG.open("rb") as image:
        signature = image.read(24)
    if signature[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("Pillow did not produce a PNG")
    width, height = struct.unpack(">II", signature[16:24])
    if (width, height) != (1280, 640):
        raise SystemExit(f"Expected 1280x640, got {width}x{height}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--terminal-only", action="store_true", help="skip rendering site/og.png")
    args = parser.parse_args()
    message = generate_message()
    render_terminal(message)
    if not args.terminal_only:
        render_og()
    print(f"rendered {TERMINAL.relative_to(ROOT)}")
    if not args.terminal_only:
        print(f"rendered {OG.relative_to(ROOT)} (1280x640)")


if __name__ == "__main__":
    main()
